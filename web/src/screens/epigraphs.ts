/**
 * The epigraphs under the home greeting (spec H1 §5, D3). Each one
 * is a short line from a source in the public domain or from a work
 * of the US government. The wording was checked against the page
 * named in `source`. Games Workshop text is out by ruling D3.
 *
 * The government lines come from CIA-stamped scans of releases of
 * the Stargate files. A 1983 finding is a claim the report made, and
 * the attribution says whose it is.
 */

export type EpigraphRights =
  | "public-domain"
  | "us-government"
  | "owner-supplied";

export interface Epigraph {
  readonly text: string;
  readonly rights: EpigraphRights;
  /** Who wrote it, with the translator when there is one. */
  readonly author: string;
  /** The work, with the place in it when that helps. */
  readonly work: string;
  /**
   * Where the wording was checked, or for an owner-supplied line the
   * book, codex, or page the owner named. Not shown on the page.
   */
  readonly source: string;
}

